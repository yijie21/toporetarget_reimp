#!/usr/bin/env python3
"""Regenerate configs/eval_set.yaml — the frozen ContactPose evaluation set.

The primary table reports **every** grasp of the chosen participant/intent, so
no result can be attributed to dropping hard cases.  `paper_comparable` marks
the subset that matches the paper's setting: it states "We evaluate on 25 of the
28 ContactPose grasps, excluding three with deeply concave object geometry" but
does not publish the names, so we take the *three* (their count) lowest-solidity
objects (our objective, recomputable choice), where

    solidity = mesh volume / convex hull volume

Usage:
    python scripts/make_eval_set.py --grasps <grasps_root> --models <ply_dir>
"""
import argparse
from pathlib import Path

import trimesh
import yaml

from toporetarget.contactpose import list_objects, load_annotations
from toporetarget.paths import CONFIGS

N_EXCLUDED = 3          # the paper excludes exactly three grasps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grasps", required=True, help="dir holding <participant>_<intent>/")
    ap.add_argument("--models", required=True, help="dir holding <object>.ply (millimetres)")
    ap.add_argument("--participant", default="full28")
    ap.add_argument("--intent", default="use")
    ap.add_argument("--out", default=str(CONFIGS / "eval_set.yaml"))
    args = ap.parse_args()

    objects = list_objects(args.grasps, args.participant, args.intent)
    stats = {}
    for o in objects:
        m = trimesh.load(Path(args.models) / f"{o}.ply", process=False)
        try:
            solidity = float(m.volume / m.convex_hull.volume)
        except Exception:
            solidity = float("nan")
        ann = load_annotations(args.grasps, o, args.participant, args.intent)
        stats[o] = dict(solidity=round(solidity, 4),
                        watertight=bool(m.is_watertight),
                        faces=int(len(m.faces)),
                        bimanual=bool(ann["hands"][0]["valid"]
                                      and ann["hands"][1]["valid"]))

    excluded = sorted(sorted(objects, key=lambda o: stats[o]["solidity"])[:N_EXCLUDED])
    cfg = dict(
        dataset="contactpose", participant=args.participant, intent=args.intent,
        hand="right", n_objects=len(objects), objects=sorted(objects),
        paper_comparable=dict(
            rule=("the paper excludes three grasps with 'deeply concave object "
                  "geometry' without naming them; we exclude the three lowest by "
                  "solidity = mesh_volume / convex_hull_volume"),
            excluded=excluded, n=len(objects) - len(excluded)),
        object_stats=stats,
    )
    with open(args.out, "w") as f:
        f.write("# Frozen ContactPose evaluation set - generated by "
                "scripts/make_eval_set.py, do not hand-edit.\n"
                "# The primary table reports ALL objects; `paper_comparable` marks the\n"
                "# subset matching the paper's stated exclusion of concave geometry.\n")
        yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
    print(f"{len(objects)} objects -> {args.out}; paper-comparable excludes {excluded}")


if __name__ == "__main__":
    main()
